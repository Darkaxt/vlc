// Behavioral contract for the exact JS library loaded by the native Qt UI.
import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const file=new URL('../../modules/gui/qt/player/qml/PlayerLayoutRules.js',import.meta.url);
const context=vm.createContext({});
vm.runInContext(fs.readFileSync(file,'utf8').replace(/^\.pragma library\s*/,''),context);
const rules=vm.runInContext('({defaults,currentStockStore,validateLayout,validateStore,moveControl})',context);
const plain=value=>JSON.parse(JSON.stringify(value));
const layout=plain(rules.defaults());
assert.equal(rules.validateLayout(layout),true,'the existing player layout is accepted');
assert.deepEqual(layout.bottomRight,['mute','volume','audio','subtitles','tools','queue'],'stock control order follows the rendered reference');
const legacy=plain(layout);legacy.bottomRight=['mute','volume','tools','subtitles','audio','queue'];
const legacyStore={version:1,layout:legacy,profiles:[],selected:''};
assert.deepEqual(plain(rules.currentStockStore(legacyStore)).layout,layout,'an untouched unnamed stock layout adopts the corrected defaults');
assert.deepEqual(legacyStore.layout,legacy,'the stored source is not mutated or rewritten');
const custom=plain(legacyStore);custom.layout.topRight.push('speed');
assert.deepEqual(plain(rules.currentStockStore(custom)),custom,'custom arrangements retain every position');
const selected=plain(legacyStore);selected.selected='Movies';
assert.deepEqual(plain(rules.currentStockStore(selected)),selected,'a selected named profile retains its saved arrangement');
const moved=plain(rules.moveControl(layout,'bottomLeft',0,'topRight',0));
assert.equal(moved.bottomLeft.includes('previous'),false);
assert.equal(moved.topRight[0],'previous','cross-zone movement inserts the actual control');
assert.equal(layout.bottomLeft[0],'previous','draft changes do not mutate the accepted layout');
const reordered=plain(rules.moveControl(layout,'bottomLeft',0,'bottomLeft',3));
assert.deepEqual(reordered.bottomLeft,['play','next','previous']);
const duplicate=plain(layout);duplicate.topRight.push('play');
assert.equal(rules.validateLayout(duplicate),false,'duplicate action identities are rejected');
const unknown=plain(layout);unknown.topRight.push('unknown-control');
assert.equal(rules.validateLayout(unknown),false,'unknown controls cannot enter a saved layout');
const empty=plain(layout);for(const zone in empty)empty[zone]=[];
assert.equal(rules.validateLayout(empty),true,'reset and editing remain possible with no optional controls');
const settings={theme:2,accent:'system',grid:false,remaining:true};
const store={version:1,layout,profiles:[{name:'Movies',layout,settings}],selected:'Movies'};
assert.equal(rules.validateStore(store),true);
assert.equal(rules.validateStore({...store,version:2}),false,'newer state stays read-only');
assert.equal(rules.validateStore({...store,profiles:[...store.profiles,...store.profiles]}),false,'ambiguous profile names are rejected');
assert.equal(rules.validateStore({...store,selected:'missing'}),false,'selected profile must exist');
assert.equal(rules.validateStore({...store,profiles:[{name:'Movies',layout,settings:{...settings,theme:99}}]}),false);
assert.equal(rules.validateStore({...store,profiles:[{name:'Movies',layout,settings:{...settings,credentials:'secret'}}]}),false,'profiles cannot absorb unlisted private settings');
console.log('Layout movement, draft isolation, identity validation and covered-profile settings verified.');
